/**
 * Emit Netlify's _redirects from the shared map.
 *
 * A static export cannot use Next's `redirects()`, so the deploy needs its own
 * copy. Generating it here rather than hand-maintaining a second list is what
 * stops the two from drifting.
 */
import { writeFile, mkdir } from "node:fs/promises";
import { join, resolve } from "node:path";
import { redirects } from "../redirects.mjs";

const root = resolve(import.meta.dirname, "..");
const lines = Object.entries(redirects).map(
  ([from, to]) => `${from}  ${to}  301!`
);

// 301! forces the redirect even when a file exists at the old path.
const body = `# Generated by scripts/write-redirects.mjs — do not edit.\n${lines.join("\n")}\n`;

await mkdir(join(root, "public"), { recursive: true });
await writeFile(join(root, "public/_redirects"), body, "utf8");
console.log(`redirects: wrote ${lines.length} rules to public/_redirects`);
